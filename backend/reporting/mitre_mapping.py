"""MITRE ATT&CK (Mobile) mapping for the SOC heatmap.

Technique names and tactics come from MITRE's official ATT&CK Mobile data at a
pinned version (data/mitre/attack-mobile.json, regenerated by
scripts/update_attack_mobile.py), not from a hand-written table.

Every mapped technique records the STRONGEST evidence behind it:
    permission  <  api_call  <  runtime
  permission: a declared permission set enables the capability (knowledge graph)
  api_call:   app code calls the relevant API / runs the check (static bytecode)
  runtime:    observed in the sandbox
"""
from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

logger = logging.getLogger(__name__)

ATTACK_DATA = Path(__file__).resolve().parents[2] / "data" / "mitre" / "attack-mobile.json"
STRENGTH_ORDER = {"permission": 1, "api_call": 2, "runtime": 3}

# Static API-usage rules (static_analysis/api_usage.py) -> Mobile techniques.
API_RULE_TECHNIQUES: dict[str, list[str]] = {
    "sms_send": ["T1582"],                 # SMS Control
    "sms_read_incoming": ["T1636.004"],    # Protected User Data: SMS Messages
    "sms_inbox_query": ["T1636.004"],
    "a11y_service": ["T1453"],             # Abuse Accessibility Features
    "a11y_actions": ["T1453"],
    "overlay_window": ["T1417.002"],       # Input Capture: GUI Input Capture
    "device_identifiers": ["T1426"],       # System Information Discovery
}

# Rules (scoring/rules_engine.py) -> the API-usage categories they judge. When a rule
# fires, those observations are mapped even if the per-category table didn't mark them
# suspicious (it only knows a few categories).
RULE_API_CATEGORIES: dict[str, set[str]] = {
    "R001_SMS_INTERCEPT_NONCOMM": {"sms"},
    "R002_A11Y_OVERLAY": {"accessibility", "overlay", "sms"},
    "R002B_A11Y_OVERLAY_ALONE": {"accessibility", "overlay"},
}

# Sandbox runtime behaviours -> Mobile techniques.
RUNTIME_BEHAVIOR_TECHNIQUES: dict[str, str] = {
    "sms_interception": "T1636.004",
    "accessibility_abuse": "T1453",
    "overlay_activity": "T1516",           # Input Injection
}


@lru_cache(maxsize=1)
def attack_data() -> dict:
    return json.loads(ATTACK_DATA.read_text(encoding="utf-8"))


def attack_version() -> str:
    return attack_data()["attack_version"]


@dataclass
class MappedTechnique:
    technique_id: str
    technique_name: str
    tactic: str
    evidence_refs: list[str] = field(default_factory=list)
    evidence_strength: str = "permission"
    attack_version: str = ""


def _tactic_label(phase: str) -> str:
    return phase.replace("-", " ").title()


def resolve(technique_id: str, evidence_refs: list[str] | None = None,
            evidence_strength: str = "permission") -> MappedTechnique:
    meta = attack_data()["techniques"].get(technique_id)
    if meta is None:
        logger.warning("Technique %s is not in ATT&CK Mobile v%s", technique_id, attack_version())
        name, tactic = f"Not in ATT&CK Mobile v{attack_version()}", "Unknown"
    else:
        name = meta["full_name"]
        if meta["revoked"] or meta["deprecated"]:
            name += f" (deprecated/revoked in ATT&CK Mobile v{attack_version()})"
        tactic = ", ".join(_tactic_label(t) for t in meta["tactics"]) or "Unknown"
    return MappedTechnique(technique_id, name, tactic, evidence_refs or [],
                           evidence_strength, attack_version())


class HeatmapBuilder:
    """Collect technique -> (evidence ids, strongest evidence) from all sources."""

    def __init__(self) -> None:
        self._refs: dict[str, list[str]] = {}
        self._strength: dict[str, str] = {}

    def add(self, technique_id: str, evidence_id: str | None, strength: str) -> None:
        refs = self._refs.setdefault(technique_id, [])
        if evidence_id and evidence_id not in refs:
            refs.append(evidence_id)
        current = self._strength.get(technique_id)
        if current is None or STRENGTH_ORDER[strength] > STRENGTH_ORDER[current]:
            self._strength[technique_id] = strength

    def build(self) -> list[MappedTechnique]:
        return [resolve(tid, self._refs[tid], self._strength[tid]) for tid in sorted(self._refs)]


def build_heatmap(technique_ids_with_refs: dict[str, list[str]],
                  strength: str = "permission") -> list[MappedTechnique]:
    """technique_id -> evidence_ids  ==>  mapped techniques (single evidence strength)."""
    return [resolve(tid, refs, strength) for tid, refs in sorted(technique_ids_with_refs.items())]
